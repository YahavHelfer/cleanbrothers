import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const harness=path.dirname(fileURLToPath(import.meta.url));
const source=path.resolve(process.argv[2]??'.');
const evidence=path.resolve(process.argv[3]??'ci-evidence');
fs.mkdirSync(evidence,{recursive:true});
const assertions=path.join(evidence,'assertions.jsonl');fs.writeFileSync(assertions,'');
const tests=fs.readdirSync(path.join(source,'tests')).filter(x=>x.endsWith('.test.mjs')).sort().map(x=>'tests/'+x);
const result=spawnSync(process.execPath,['--require',path.join(harness,'assert-evidence.cjs'),'--experimental-strip-types','--test','--test-reporter=spec',...tests],{cwd:source,env:{...process.env,FORCE_COLOR:'0',QA_ASSERTS:assertions},encoding:'utf8',maxBuffer:50*1024*1024});
const output=(result.stdout??'')+(result.stderr??'');fs.writeFileSync(path.join(evidence,'tests.log'),output);
if(result.error||result.signal)throw result.error??new Error('Test process killed: '+result.signal);
const failures=[...output.split('✖ failing tests:')[0].matchAll(/^✖ (.+?) \([\d.]+ms\)$/gm)].map(x=>x[1]).sort();
const policy=JSON.parse(fs.readFileSync(path.join(harness,'known-failures.json'),'utf8'));
const actual=fs.readFileSync(assertions,'utf8').trim().split('\n').filter(Boolean).map(x=>JSON.parse(x));
const fingerprint=x=>[x.location,x.actual,x.expected].join(':');
assert.deepEqual(failures,[...policy.test_names].sort(),'New, missing or renamed failure');
assert.deepEqual(actual.map(fingerprint).sort(),policy.assertions.map(fingerprint).sort(),'Known failure changed its assertion or full values');
assert.equal(result.status,1,'Expected the raw suite to report its 12 known failures');
const count=Number(output.match(/^ℹ tests (\d+)$/m)?.[1]);
const passed=Number(output.match(/^ℹ pass (\d+)$/m)?.[1]);
const failed=Number(output.match(/^ℹ fail (\d+)$/m)?.[1]);
const baseline=process.argv.includes('--baseline');
assert.equal(count,baseline?545:553);assert.equal(failed,12);assert.equal(passed,count-12);
assert.match(output,/^ℹ skipped 0$/m);assert.match(output,/^ℹ cancelled 0$/m);
const summary={rawSuite:'failed',total:count,passed,knownFailures:failed,newFailures:0,gate:'passed-with-frozen-baseline-debt',baseline:policy.baseline,source:policy.source};
fs.writeFileSync(path.join(evidence,'summary.json'),JSON.stringify(summary,null,2)+'\n');console.log(summary);
